using System;
using System.Collections.Generic;

namespace MTile.Net;

// What the routing executor's jump gesture can reach, measured — not modelled
// (Plans/BOT_ROUTING_PLAN.md M1). Movement is solver-driven (the lattice corrector
// shapes every arc), so the planner trusts only these measured envelopes.
//
// Coordinates: a stand node (x, y) is the empty cell a standing body's feet are in, with
// solid floor at (x, y + 1). A jump entry (Dx, Dy) goes from the takeoff node — the last
// floor cell before an edge, facing +x — to a destination platform whose first column is
// Dx cells further on and whose top is Dy cells higher (negative = lower). Mirrored for -x.
//
// The gesture (MTile.Tests.Sim.ZzzRouteCalibration): walk toward the edge, press Space
// when the body centre is Lead px short of the takeoff cell's far edge — or, for Stand,
// stop at the edge first and press from rest; Walk never presses (walk off a ledge, or
// step up one cell) — then hold Space for HoldFrames. The travel direction is held until
// the body centre passes the middle of the destination's first column, then released
// (the brake: without it a held direction overshoots a narrow top by 3–4 columns).
//
// Entries are generated by ZzzRouteCalibration.ReachTable (JumpTable.g.cs): a takeoff is
// kept only if it still lands with the start nudged (lead +-2 px, a shorter run-up), and
// each entry carries the cells the body swept (to reject arcs that clip terrain) and the
// columns it can land in (narrow tops need a short overshoot).
// BotManeuverRouteJumpTableTests re-flies a sample so a movement retune that breaks the
// table fails loudly instead of silently stranding the bot.
public static partial class JumpTable
{
    public enum Takeoff : byte { Walk, Stand, Edge, Half, One, Two }

    public const int HoldFrames = 30;
    // Stand: body centre this far (cells) short of the edge, at rest. Others: run-up cells
    // walked before the press, and the press lead (px short of the edge).
    public const float StandBack = 0.6f;
    public const float RunUpCells = 5f;
    public static float Lead(Takeoff t) => t switch
    {
        Takeoff.Walk => 0f, Takeoff.Edge => 0f, Takeoff.Half => 5.5f, Takeoff.One => 11f, Takeoff.Two => 22f, _ => 0f,
    };

    public readonly struct Entry
    {
        public readonly sbyte Dx, Dy;
        public readonly Takeoff Takeoff;
        public readonly short Frames;          // press → landed, worst variant
        public readonly sbyte LandMin, LandMax; // landing column offsets from the takeoff column
        public readonly float Hurt;            // fall-impact HP, worst variant
        // Swept cells: per column offset c = 0..(Sweep.Length/2 - 1), rows [top, bottom]
        // relative to the takeoff node's row (negative = above).
        public readonly sbyte[] Sweep;
        public Entry(int dx, int dy, Takeoff t, int frames, int landMin, int landMax, float hurt, sbyte[] sweep)
        {
            Dx = (sbyte)dx; Dy = (sbyte)dy; Takeoff = t; Frames = (short)frames;
            LandMin = (sbyte)landMin; LandMax = (sbyte)landMax; Hurt = hurt; Sweep = sweep;
        }
        public int SweepColumns => Sweep.Length / 2;
        public int SweepTop(int c) => Sweep[2 * c];
        public int SweepBottom(int c) => Sweep[2 * c + 1];
    }

    private static Dictionary<(int, int), Entry> _byOffset;

    public static IReadOnlyList<Entry> All => Entries;

    public static bool TryGet(int dx, int dy, out Entry e)
    {
        if (_byOffset == null)
        {
            var d = new Dictionary<(int, int), Entry>();
            foreach (var x in Entries) d[(x.Dx, x.Dy)] = x;
            _byOffset = d;
        }
        return _byOffset.TryGetValue((dx, dy), out e);
    }
}
